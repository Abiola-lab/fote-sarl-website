const SUPPORTED_LANGS = ['fr', 'pt', 'en'];
const DEFAULT_LANG = 'fr';

function getTranslation(lang, key) {
  const parts = key.split('.');
  let node = translations[lang];
  for (const part of parts) {
    if (node == null) return null;
    node = node[part];
  }
  return typeof node === 'string' ? node : null;
}

function getStoredLang() {
  try {
    const stored = localStorage.getItem('fote-lang');
    if (stored && SUPPORTED_LANGS.includes(stored)) return stored;
  } catch (e) {
    /* localStorage unavailable, ignore */
  }
  return null;
}

function setStoredLang(lang) {
  try {
    localStorage.setItem('fote-lang', lang);
  } catch (e) {
    /* localStorage unavailable, ignore */
  }
}

function applyTranslations(lang) {
  document.documentElement.setAttribute('lang', lang);

  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    const value = getTranslation(lang, key) || getTranslation(DEFAULT_LANG, key);
    if (value != null) el.textContent = value;
  });

  document.querySelectorAll('[data-i18n-attr]').forEach((el) => {
    let map;
    try {
      map = JSON.parse(el.getAttribute('data-i18n-attr'));
    } catch (e) {
      return;
    }
    Object.entries(map).forEach(([attr, key]) => {
      const value = getTranslation(lang, key) || getTranslation(DEFAULT_LANG, key);
      if (value != null) el.setAttribute(attr, value);
    });
  });

  const titleKey = document.body.getAttribute('data-page-title-key');
  if (titleKey) {
    const title = getTranslation(lang, titleKey) || getTranslation(DEFAULT_LANG, titleKey);
    if (title) document.title = title;
  }

  document.querySelectorAll('[data-lang-option]').forEach((btn) => {
    const isActive = btn.getAttribute('data-lang-option') === lang;
    btn.classList.toggle('bg-white/20', isActive);
    btn.classList.toggle('font-semibold', isActive);
    btn.setAttribute('aria-current', isActive ? 'true' : 'false');
  });
}

function setLanguage(lang) {
  if (!SUPPORTED_LANGS.includes(lang)) lang = DEFAULT_LANG;
  setStoredLang(lang);
  applyTranslations(lang);
}

document.addEventListener('DOMContentLoaded', () => {
  const initialLang = getStoredLang() || DEFAULT_LANG;
  applyTranslations(initialLang);

  document.querySelectorAll('[data-lang-option]').forEach((btn) => {
    btn.addEventListener('click', () => setLanguage(btn.getAttribute('data-lang-option')));
  });
});
